"""Human-readable views of the rule registry: list, explain and the generated docs/rules.md."""

from __future__ import annotations

import json
import textwrap
from typing import Any, List

from agency_guardrails import registry
from agency_guardrails.model import Rule

PACK_BLURBS = {
    "eu-marketing": "Consumer-protection patterns for EU-facing marketing copy.",
    "aeo-seo": "Structure checks for articles that should rank and be quoted by AI answers.",
    "house-style": "Characters and words your brand never ships.",
    "secrets": "Credentials that must never be written into content, config or code.",
    "deploy-safety": "Action rules that stop agents from changing production directly (PreToolUse).",
}


def _fmt_default(value: Any) -> str:
    return json.dumps(value, ensure_ascii=True)


def rules_text(rules: List[Rule]) -> str:
    width = max((len(r.title) for r in rules), default=10)
    lines = []
    for pack in sorted({r.pack for r in rules}):
        lines.append("%s: %s" % (pack, PACK_BLURBS.get(pack, "")))
        for r in [r for r in rules if r.pack == pack]:
            lines.append("  %-10s  %-5s  %-*s  %s" % (r.id, r.severity, width, r.title, r.citation))
        lines.append("")
    return "\n".join(lines)


def rules_json(rules: List[Rule]) -> str:
    return json.dumps([r.describe() for r in rules], indent=2, ensure_ascii=True) + "\n"


def explain(rule: Rule) -> str:
    wrap = lambda s: textwrap.fill(s, width=88, initial_indent="  ", subsequent_indent="  ")  # noqa: E731
    out = [
        "%s  %s" % (rule.id, rule.title),
        "",
        "pack: %s    severity: %s    kind: %s    applies to: %s"
        % (rule.pack, rule.severity, rule.kind, ", ".join(rule.applies_to)),
        "",
        "Why",
        wrap(rule.rationale),
        "",
        "Fix",
        wrap(rule.fix),
        "",
        "Source",
        "  " + rule.citation,
    ]
    if rule.options:
        out += ["", "Options (set in [%s] or [rules.%s])" % (rule.pack, rule.id)]
        for name, (default, help_text) in rule.options.items():
            out.append("  %s = %s" % (name, _fmt_default(default)))
            out.append(textwrap.fill(help_text, width=88, initial_indent="      ", subsequent_indent="      "))
    out += ["", "Silence one line with a comment containing: guardrails-ignore: %s" % rule.id]
    return "\n".join(out) + "\n"


def rules_markdown(rules: List[Rule]) -> str:
    out = [
        "# Rule reference",
        "",
        "<!-- Generated by scripts/gen_rules_doc.py from the rule registry. Do not edit by hand. -->",
        "",
        "[Back to README](../README.md)",
        "",
        "Every rule has an id, a default severity, the reason it exists, how to fix a finding and a link to "
        "the primary source. Run `guardrails explain <ID>` for the same text in a terminal. How the sources "
        "were chosen and how each rule is tested is in [methodology.md](methodology.md).",
        "",
        "> [!WARNING]",
        "> These rules are engineering heuristics that make a person look before content ships. They are not "
        "legal advice and passing them does not make copy compliant.",
        "",
        "| ID | Pack | Severity | Title |",
        "| --- | --- | --- | --- |",
    ]
    for r in rules:
        anchor = r.id.lower()
        out.append("| [%s](#%s) | %s | %s | %s |" % (r.id, anchor, r.pack, r.severity, r.title.replace("|", "\\|")))
    for pack in sorted({r.pack for r in rules}):
        out += ["", "## Pack: %s" % pack, "", PACK_BLURBS.get(pack, "")]
        for r in [r for r in rules if r.pack == pack]:
            out += [
                "",
                "### %s" % r.id,
                "",
                "**%s** (%s, %s rule, applies to: %s)" % (r.title, r.severity, r.kind, ", ".join(r.applies_to)),
                "",
                r.rationale,
                "",
                "**Fix:** %s" % r.fix,
                "",
                "**Source:** <%s>" % r.citation,
            ]
            if r.options:
                out += ["", "| Option | Default | Description |", "| --- | --- | --- |"]
                for name, (default, help_text) in r.options.items():
                    shown = _fmt_default(default)
                    if len(shown) > 80:
                        shown = shown[:77] + "..."
                    out.append("| `%s` | `%s` | %s |" % (name, shown.replace("|", "\\|"), help_text.replace("|", "\\|")))
    out += [
        "",
        "[Back to README](../README.md)",
        "",
        "---",
        "",
        "Built by [Chris Fountoulis](https://chrisfountoulis.com) at "
        "[Growth Of Influence](https://growthofinfluence.com).",
    ]
    return "\n".join(out) + "\n"


def all_rules_markdown() -> str:
    return rules_markdown(registry.all_rules())
